import { BadRequestException, ForbiddenException, Injectable } from '@nestjs/common'
import { DatabaseService, type Invitation } from '@vyrak/database'

import { InviteMemberDto } from './dto/invite-member.dto'
import { InvitationResponse } from './dto/organization-response.dto'

@Injectable()
export class InvitationsService {
  constructor(private readonly prisma: DatabaseService) {}

  /**
   * Invite member vào organization (admin/owner only)
   */
  async invite(organizationId: string, inviterId: string, data: InviteMemberDto): Promise<InvitationResponse> {
    // Verify inviter permission (admin or owner)
    await this.verifyPermission(organizationId, inviterId, ['owner', 'admin'])

    // Check if already member
    const existingMember = await this.prisma.client.member.findFirst({
      where: {
        organizationId,
        user: { email: data.email },
      },
    })

    if (existingMember) {
      throw new BadRequestException('User is already a member')
    }

    // Cancel pending invitations for same email
    await this.prisma.client.invitation.updateMany({
      where: {
        organizationId,
        email: data.email,
        status: 'pending',
      },
      data: { status: 'cancelled' },
    })

    // Create invitation (token will be generated by database)
    const expiresAt = new Date(Date.now() + 48 * 60 * 60 * 1000) // 48 hours

    const invitation = await this.prisma.client.invitation.create({
      data: {
        organizationId,
        email: data.email,
        role: data.role,
        inviterId,
        status: 'pending',
        expiresAt,
      },
      include: {
        organization: {
          select: {
            id: true,
            name: true,
            slug: true,
          },
        },
      },
    })

    // TODO: Send invitation email
    // await this.emailService.sendInvitation(invitation)

    return {
      id: invitation.id,
      email: invitation.email,
      role: invitation.role,
      status: invitation.status,
      expiresAt: invitation.expiresAt,
      createdAt: invitation.createdAt,
      organization: invitation.organization,
    }
  }

  /**
   * Accept invitation
   */
  async accept(invitationId: string, userId: string): Promise<InvitationResponse> {
    const invitation = await this.prisma.client.invitation.findUnique({
      where: { id: invitationId },
      include: {
        organization: {
          select: {
            id: true,
            name: true,
            slug: true,
          },
        },
      },
    })

    if (!invitation || invitation.status !== 'pending') {
      throw new BadRequestException('Invalid or expired invitation')
    }

    if (new Date() > invitation.expiresAt) {
      throw new BadRequestException('Invitation has expired')
    }

    // Verify user email matches
    const user = await this.prisma.client.user.findUnique({
      where: { id: userId },
    })

    if (!user || user.email !== invitation.email) {
      throw new ForbiddenException('Email does not match invitation')
    }

    // Create membership và update invitation status atomically
    await this.prisma.$transaction([
      this.prisma.client.member.create({
        data: {
          organizationId: invitation.organizationId,
          userId,
          role: invitation.role,
        },
      }),
      this.prisma.client.invitation.update({
        where: { id: invitationId },
        data: { status: 'accepted' },
      }),
    ])

    return {
      id: invitation.id,
      email: invitation.email,
      role: invitation.role,
      status: 'accepted',
      expiresAt: invitation.expiresAt,
      createdAt: invitation.createdAt,
      organization: invitation.organization,
    }
  }

  /**
   * Reject invitation
   */
  async reject(invitationId: string, userId: string): Promise<void> {
    const invitation = await this.prisma.client.invitation.findUnique({
      where: { id: invitationId },
    })

    if (!invitation || invitation.status !== 'pending') {
      throw new BadRequestException('Invalid invitation')
    }

    // Verify user email matches
    const user = await this.prisma.client.user.findUnique({
      where: { id: userId },
    })

    if (!user || user.email !== invitation.email) {
      throw new ForbiddenException('Email does not match invitation')
    }

    await this.prisma.client.invitation.update({
      where: { id: invitationId },
      data: { status: 'rejected' },
    })
  }

  /**
   * List pending invitations for organization (admin/owner only)
   */
  async listForOrganization(organizationId: string, userId: string): Promise<InvitationResponse[]> {
    await this.verifyPermission(organizationId, userId, ['owner', 'admin'])

    const invitations = await this.prisma.client.invitation.findMany({
      where: {
        organizationId,
        status: 'pending',
      },
      orderBy: { createdAt: 'desc' },
    })

    return invitations.map((inv: Invitation): InvitationResponse => ({
      id: inv.id,
      email: inv.email,
      role: inv.role,
      status: inv.status,
      expiresAt: inv.expiresAt,
      createdAt: inv.createdAt,
    }))
  }

  /**
   * List user's pending invitations by user ID
   */
  async listForUserId(userId: string): Promise<InvitationResponse[]> {
    const user = await this.prisma.client.user.findUnique({
      where: { id: userId },
    })

    if (!user) {
      return []
    }

    return this.listForUser(user.email)
  }

  /**
   * List user's pending invitations by email
   */
  async listForUser(userEmail: string): Promise<InvitationResponse[]> {
    const invitations = await this.prisma.client.invitation.findMany({
      where: {
        email: userEmail,
        status: 'pending',
        expiresAt: {
          gt: new Date(),
        },
      },
      include: {
        organization: {
          select: {
            id: true,
            name: true,
            slug: true,
          },
        },
      },
      orderBy: { createdAt: 'desc' },
    })

    return invitations.map(
      (inv: Invitation & { organization: { id: string; name: string; slug: string } }): InvitationResponse => ({
        id: inv.id,
        email: inv.email,
        role: inv.role,
        status: inv.status,
        expiresAt: inv.expiresAt,
        createdAt: inv.createdAt,
        organization: inv.organization,
      })
    )
  }

  private async verifyPermission(organizationId: string, userId: string, allowedRoles: string[]) {
    const membership = await this.prisma.client.member.findUnique({
      where: {
        organizationId_userId: { organizationId, userId },
      },
    })

    if (!membership || !allowedRoles.includes(membership.role)) {
      throw new ForbiddenException('Insufficient permissions')
    }

    return membership
  }
}
