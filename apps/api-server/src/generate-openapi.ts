/**
 * Standalone script: boots the NestJS app without listening on a port,
 * generates the OpenAPI document, writes it as YAML to docs/openapi.yaml,
 * then exits cleanly.
 *
 * This script generates the OpenAPI specification (openapi.yml) from NestJS decorators
 * without requiring a real database connection.
 *
 * How it works:
 * 1. Set SKIP_DB_CONNECTION=true to prevent DatabaseService from connecting
 * 2. Set placeholder DATABASE__URL to bypass Prisma client initialization check
 * 3. Create NestJS app with Express platform
 * 4. Extract OpenAPI metadata from controller decorators using SwaggerModule
 * 5. cleanupOpenApiDoc resolves nestjs-zod schemas into proper OpenAPI definitions
 * 6. Write the specification to openapi.yml
 *
 * This approach allows CI/CD to generate API docs without database setup,
 * while keeping all service implementations intact (no mocking needed).
 *
 * Usage: tsx src/generate-openapi.ts
 */
import { NestFactory } from '@nestjs/core'
import { NestExpressApplication } from '@nestjs/platform-express'
import { DocumentBuilder, SwaggerModule } from '@nestjs/swagger'
import { config as loadDotenv } from 'dotenv'
import { dump as yamlDump } from 'js-yaml'
import fs from 'node:fs'
import path from 'node:path'

import './load-env'
import { AppOpenApiModule } from './app/app-openapi.module'

function findProjectRoot(): string {
  let currentDir = process.cwd()
  while (currentDir !== path.dirname(currentDir)) {
    if (fs.existsSync(path.join(currentDir, 'config')) && fs.existsSync(path.join(currentDir, 'pnpm-workspace.yaml'))) {
      return currentDir
    }
    currentDir = path.dirname(currentDir)
  }
  return process.cwd()
}

/** Load api-server .env when present; fill placeholders so CustomConfig passes without real infra. */
function bootstrapEnvForOpenApiGeneration(): void {
  const projectRoot = findProjectRoot()
  const apiEnvPath = path.join(projectRoot, 'apps/api-server/.env')
  if (fs.existsSync(apiEnvPath)) {
    loadDotenv({ path: apiEnvPath })
  }

  process.env.SKIP_DB_CONNECTION = 'true'
  process.env.SKIP_WEBSOCKET = 'true' // Skip WebSocket gateway during OpenAPI generation

  const defaults: Record<string, string> = {
    DATABASE__URL: 'postgresql://localhost:5432/placeholder',
    REDIS__URL: 'redis://localhost:6379',
    S3__ENDPOINT: 'http://localhost:4566',
    S3__REGION: 'us-east-1',
    S3__BUCKET: 'vyrak-artifacts',
    S3__ACCESS_KEY_ID: 'test',
    S3__SECRET_ACCESS_KEY: 'test',
    S3__FORCE_PATH_STYLE: 'true',
    WORKSPACE__MAIN_REPOS_PATH: '/tmp/vyrak-openapi',
    WORKSPACE__WORKSPACES_PATH: '/tmp/vyrak-workspaces',
    FRONTEND_URL: 'http://localhost:5173',
    GIT__GITHUB_APP__APP_ID: '123456',
    GIT__GITHUB_APP__INSTALLATION_ID: '789012',
    GIT__GITHUB_APP__PRIVATE_KEY: '-----BEGIN RSA PRIVATE KEY-----\nplaceholder\n-----END RSA PRIVATE KEY-----',
  }

  for (const [key, value] of Object.entries(defaults)) {
    if (!process.env[key]) {
      process.env[key] = value
    }
  }
}

bootstrapEnvForOpenApiGeneration()

