/**
 * Fix nullable types in OpenAPI spec generated by nestjs-zod
 * Converts anyOf: [{ type: 'string' }, { type: 'null' }] to type: 'string', nullable: true
 */
function fixNullableTypes(obj: unknown): void {
  if (typeof obj !== 'object' || obj === null) {
    return
  }

  const record = obj as Record<string, unknown>

  // Check if this is an anyOf with null type
  if (record.anyOf && Array.isArray(record.anyOf)) {
    const nullIndex = record.anyOf.findIndex((item: unknown) => {
      return typeof item === 'object' && item !== null && (item as Record<string, unknown>).type === 'null'
    })
    if (nullIndex !== -1) {
      // Remove the null type
      const types = record.anyOf.filter((item: unknown) => {
        return !(typeof item === 'object' && item !== null && (item as Record<string, unknown>).type === 'null')
      })

      if (types.length === 1) {
        // Replace anyOf with the single type and add nullable: true
        const singleType = types[0] as Record<string, unknown>
        delete record.anyOf
        Object.assign(record, singleType)
        record.nullable = true
      } else if (types.length > 1) {
        // Keep anyOf but remove null type and add nullable: true
        record.anyOf = types
        record.nullable = true
      }
    }
  }

  // Check if type is an array [type, 'null']
  if (Array.isArray(record.type) && record.type.includes('null')) {
    const types = record.type.filter((t: unknown) => t !== 'null')
    if (types.length === 1) {
      record.type = types[0]
      record.nullable = true
    }
  }

  // Recursively process all properties
  for (const key in record) {
    if (typeof record[key] === 'object' && record[key] !== null) {
      fixNullableTypes(record[key])
    }
  }
}

async function generateOpenApiSpec() {
  console.log('[OpenAPI] Starting generation...')
  console.log('[OpenAPI] Current directory:', currentDir)
  console.log('[OpenAPI] SKIP_DB_CONNECTION:', process.env.SKIP_DB_CONNECTION)
  console.log('[OpenAPI] DATABASE__URL:', process.env.DATABASE__URL ? 'SET' : 'NOT SET')

  console.log('[OpenAPI] Creating NestJS app...')
  const app = await NestFactory.create<NestExpressApplication>(AppOpenApiModule, {
    logger: ['error', 'warn'], // Reduce logging noise
  })

  // Initialize the app to setup HttpAdapterHost for ClsModule
  await app.init()

  console.log('[OpenAPI] Building Swagger configuration...')
  const config = new DocumentBuilder()
    .setTitle('Vyrak API')
    .setDescription('Vyrak API documentation')
    .setVersion('1.0')
    .addBearerAuth()
    .addServer('http://localhost:3000', 'Development')
    .build()

  console.log('[OpenAPI] Creating document...')
  const document = SwaggerModule.createDocument(app, config)

  console.log('[OpenAPI] Transforming document to fix nullable types...')
  fixNullableTypes(document)

  // currentDir = apps/api-server/src → go up 3 levels to monorepo root
  const outputPath = path.resolve(currentDir, '..', '..', '..', 'openapi.yaml')
  console.log('[OpenAPI] Output path:', outputPath)

  fs.writeFileSync(outputPath, yamlDump(document, { lineWidth: 120 }), 'utf8')

  console.log(`✅ OpenAPI spec generated at: ${outputPath}`)

  await app.close()
}

generateOpenApiSpec().catch((error) => {
  console.error('❌ Error generating OpenAPI spec:')
  console.error(error)
  if (error.stack) {
    console.error('\nStack trace:')
    console.error(error.stack)
  }
  process.exit(1)
})
